/**
 * シードから仕訳帳配列を生成。
 * 初期エントリは負のidを割り当て、submitで採番する正のidと衝突させない。
 */
function seedToJournal(seed: Omit<JournalEntry, 'id'>[]): JournalEntry[] {
  let id = -1;
  return seed.map((e) => ({ ...e, id: id-- }));
}

